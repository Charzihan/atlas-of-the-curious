    // SE-Asia cluster, or two Icelandic ice caves that project to the SAME grid
    // cell) can sit on top of each other. We push coincident pairs apart with a
    // stable pairwise relaxation — every pass re-measures the current positions
    // and displaces both members of a pair by half the deficit (no cascading),
    // with the total displacement capped so a dot can never be thrown across
    // the map. The TRUE coordinates (x.pos) are still used for the ripple and
    // the hover card, so a nudged dot still points at the right place.
    // (The old algorithm read already-nudged positions of later markers and
    // produced NaN for exact coincidences, which CSS drops — throwing the dot
    // to the map's top-left corner.)
    const MIN_SEP = Math.max(20, PX * 1.8);
