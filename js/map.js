  // Reflow-free wrapping via pretext (monospace grid ⇒ chars = cells).
  function wrapLines(text, font, maxCharsPx, maxChars, lineHeight) {
    text = String(text).trim();
    if (maxChars <= 0) return [text];
    if (text.length <= maxChars) return [text];
    try {
      const pre = prepareWithSegments(text, font);
      const res = layoutWithLines(pre, maxChars * maxCharsPx, lineHeight);
      if (res && res.lines && res.lines.length) {
        return res.lines.map((l) => l.text).filter((t) => t.length);
      }
    } catch (e) { /* fall back below */ }
    const words = text.split(/\s+/);
    const lines = [];
    let cur = "";
    for (const w of words) {
      if (!cur) cur = w;
      else if ((cur + " " + w).length <= maxChars) cur += " " + w;
      else { lines.push(cur); cur = w; }
    }
    if (cur) lines.push(cur);
    return lines;
  }

  function parseCoords(s) {
    const m = /(-?\d+(?:\.\d+)?)\s*°?\s*([NSns])[\s,]+(-?\d+(?:\.\d+)?)\s*°?\s*([EWew])/.exec(s || "");
    if (!m) return null;
    return { lat: m[1] * (m[2].toUpperCase() === "S" ? -1 : 1), lon: m[3] * (m[4].toUpperCase() === "W" ? -1 : 1) };
  }
  function project(p, cols, rows, charW, lineH) {
    const c = parseCoords(p.coordinates);
    if (!c) return null;
    const col = Math.max(0, Math.min(cols - 1, Math.round(((c.lon + 180) / 360) * cols)));
    const row = Math.max(0, Math.min(rows - 1, Math.round(((90 - c.lat) / 180) * rows)));
    return { col, row, x: (col + 0.5) * charW, y: (row + 0.5) * lineH };
  }
  // Great-circle distance (km) between two lat/lon pairs.
  function distKm(a, b) {
    const R = 6371, rad = Math.PI / 180;
    const dLat = (b.lat - a.lat) * rad, dLon = (b.lon - a.lon) * rad;
    const s = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dLon / 2) ** 2;
    return 2 * R * Math.asin(Math.min(1, Math.sqrt(s)));
  }
  const fmtKm = (km) => km < 1000 ? Math.round(km) + " km" : (km / 1000).toFixed(1) + "k km";

  // Cell kind: 0 = water, 1 = land (color = palette index).
  const kind = new Uint8Array(COLS * ROWS);
  const cellColor = new Uint8Array(COLS * ROWS);
  const cellGlyph = new Uint8Array(COLS * ROWS);
  for (let r = 0; r < ROWS; r++) {
    const gRow = MAP.glyphs[r], cRow = MAP.colors[r];
    for (let c = 0; c < COLS; c++) {
      const i = r * COLS + c;
      if (cRow[c] !== " ") {
        kind[i] = 1;
        cellColor[i] = cRow.charCodeAt(c) - 65; // 'A' → 0
        cellGlyph[i] = gRow.charCodeAt(c);
      }
    }
  }

  // Neighbour lists for the water-cell spring simulation.
  const neighbors = new Int32Array(COLS * ROWS * 4);
  const nCount = new Uint8Array(COLS * ROWS);
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < COLS; c++) {
      const i = r * COLS + c;
      if (kind[i]) continue;
      let n = 0;
      if (c > 0 && !kind[i - 1]) neighbors[i * 4 + n++] = i - 1;
      if (c < COLS - 1 && !kind[i + 1]) neighbors[i * 4 + n++] = i + 1;
      if (r > 0 && !kind[i - COLS]) neighbors[i * 4 + n++] = i - COLS;
      if (r < ROWS - 1 && !kind[i + COLS]) neighbors[i * 4 + n++] = i + COLS;
      nCount[i] = n;
    }
  }
  const waterCells = [];
  for (let i = 0; i < COLS * ROWS; i++) if (!kind[i]) waterCells.push(i);

  const places = DATA.places
    .map((p) => ({ p, accent: (catById.get(p.category) || {}).accent || "#e8b45a" }))
    .filter((x) => parseCoords(x.p.coordinates));

  /* ==================================================================== *
   * Labels on the map                                                     *
   * ==================================================================== *
   *
   * Every label — a place name, a place tagline, an ocean name — is text
   * poured into *free water cells* of the same character grid the map is drawn
   * on. Three ideas hold it together:
   *
   * 1. Two masks. `kind` (built above, never changes) says which cells are
   *    land. `occupancy` is rebuilt from scratch on every placement and says
   *    which cells this frame's labels have already claimed. A cell is free
   *    when it is water and unclaimed.
   *
   * 2. Screen px, not map px. Labels counter-scale with 1/--zoom exactly like
   *    the markers, so a label keeps a constant on-screen size at any zoom.
   *    A grid cell, on the other hand, grows with the zoom: on screen it is
   *    CHARW * zoom wide. So zooming in buys the label more cells for the same
   *    number of characters — which is the whole reason the zoom tiers below
   *    can afford to show more text the closer you get.
   *
   * 3. One line per grid row. Each label line is laid out at the width of its
   *    own row's free run and painted with a line box exactly one grid row
   *    tall, so what was routed and what is painted occupy the same cells.
   *    ATLAS_MAP_DEBUG.checkLabels() re-derives those cells from the rendered
   *    geometry and walks them against the land mask, which is what makes
   *    "no label overlaps land or another label" a testable claim.
   *
   * Preparation (the expensive pretext pass) happens once per string; a zoom
   * change only re-runs routing, never `prepareWithSegments()`.
   *
   * Phase 5 moved all of that into js/labels.js — the same code, with the DOM
   * left behind — so it can run inside js/text-worker.js. What stays here is
   * the thin client: build a request, post it, and render whatever comes back
   * (dropping a reply a newer request has overtaken). When there is no worker
   * the very same pure module is called synchronously instead. */

