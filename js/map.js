    // ---- Animation loop ------------------------------------------------------
    // The sea canvas carries a wave field: three superposed traveling wave
    // trains (a long eastward swell, a slow westward set, and a fast short
    // chop) blended with the interactive ripple spring. Each water cell's
    // value maps through a glyph + luminance ramp so wave crests read as thin
    // bright lines moving across the water and calm troughs stay faint.
    // The clock resets on resume-from-off-screen so the waves continue smoothly
    // instead of jumping.
    waveT0 = performance.now();
    // Ambient wave strength (kept modest so ripples still read clearly).
    const WAVE_AMP = REDUCED ? 0.0 : 0.8;
    // Wave trains: [angular freq (rad/s), col wavenumber, row wavenumber].
    // Directions differ per train so the crests interfere and never repeat.
    const W1 = { w: 0.30, kc: 0.11, kr: 0.020, amp: 0.55 }; // long eastward swell
    const W2 = { w: 0.42, kc: -0.05, kr: 0.070, amp: 0.40 }; // slow westward set
    const W3 = { w: 1.05, kc: 0.05, kr: 0.030, amp: 0.30 };  // fast short chop
    function frame(now) {
      const t = (now - waveT0) / 1000;
      if (!viewportVisible) { loopRunning = false; return; } // off-screen: suspended
      // Spring step for the interactive ripple field.
      for (let i = 0; i < COLS * ROWS; i++) {
        const n = nCount[i];
        if (!n) continue;
        let lap = 0;
        const b4 = i * 4;
        for (let k = 0; k < n; k++) lap += disp[neighbors[b4 + k]];
        vel[i] += (lap - n * disp[i]) * SPREAD;
      }
      for (let i = 0; i < COLS * ROWS; i++) {
        if (!nCount[i]) continue;
        vel[i] += -SPRING * disp[i];
        vel[i] *= DAMP;
        disp[i] += vel[i];
      }

      sctx.clearRect(0, 0, mapW, mapH);
      const N = waterLen;
      for (let w = 0; w < N; w++) {
        const i = waterList[w];
        const c = i % COLS, r = (i / COLS) | 0;
        let density;
        if (WAVE_AMP > 0) {
          // Superposed traveling waves; the per-region phase tilt makes the
          // fronts arrive at different times so the sea shimmers rather than
          // scrolling. Normalized to 0..1, then gamma-sharpened into crests.
          const ph = phase[i];
          const a = Math.sin(t * W1.w + c * W1.kc + r * W1.kr + ph);
          const b = Math.sin(t * W2.w + c * W2.kc + r * W2.kr - ph * 0.4);
          const e = Math.sin(t * W3.w + c * W3.kc + r * W3.kr);
          let m = a * W1.amp + b * W2.amp + e * W3.amp;   // ~ -1.25 .. 1.25
          const base = (m + 1.25) / 2.5;                   // 0 .. 1
          // Gamma concentrates energy into moving crests; a regional bias
          // keeps some seas consistently rougher than others.
          density = Math.pow(base, WAVE_GAMMA) * WAVE_AMP
            + 0.10 * (waveBias[i] - 0.5);
        } else {
          density = 0.05;
        }
        // Interactive ripple: crests light up and lift, troughs dim. Added
        // after gamma so a splash punches through the ambient waves.
        const d = disp[i];
        const densityRaw = density + d * 1.5;
        const y0 = (r + 0.5) * LINEH;
        const y = y0 + Math.max(-2.4, Math.min(2.4, d)) * LIFT;
        if (densityRaw <= 0.08) continue;            // static floor shows through
        const lvl = Math.max(1, Math.min(5, (densityRaw * 6) | 0));
        sctx.fillStyle = OCEAN_COLORS[lvl];
        sctx.fillText(OCEAN_GLYPHS[lvl], c * CHARW, y);
        // Troughs dip below the baseline in a dimmer tone, so a splash has a
        // visible leading and trailing edge, not just a bright crest.
        if (d < -0.5) {
          sctx.fillStyle = "rgba(20, 40, 70, 0.55)";
          sctx.fillText("·", c * CHARW, y);
        }
      }
      // Drifting white clouds on top of the waves (fades out over Antarctica).
      drawClouds(t);
      animId = requestAnimationFrame(frame);
    }
    frameRef = frame;
